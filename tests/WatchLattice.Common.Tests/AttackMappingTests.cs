using System.Text;
using WatchLattice.Common.Alerts;
using Xunit;

namespace WatchLattice.Common.Tests;

public sealed class AttackMappingTests
{
    private const string TableStart = "<!-- attack-table:start (generated by AttackMappingTests; set WATCHLATTICE_UPDATE_DOCS=1 and run the tests to refresh) -->";
    private const string TableEnd = "<!-- attack-table:end -->";

    [Fact]
    public void EveryMappedCode_IsAClassifiedAlert()
    {
        foreach (var (module, code, _, _) in AttackMapping.Rows)
        {
            var probe = code.EndsWith('*') ? code.TrimEnd('*') + "x" : code;
            Assert.True(AlertEventIds.IsClassified(module, probe), $"{module} {code} has an ATT&CK mapping but no Event ID");
        }
    }

    [Fact]
    public void Techniques_AreListedOnce_WithWellFormedIdsAndLinks()
    {
        Assert.Equal(AttackMapping.All.Count, AttackMapping.All.Select(t => t.Id).Distinct().Count());
        Assert.All(AttackMapping.All, t => Assert.Matches(@"^T\d{4}(\.\d{3})?$", t.Id));
        Assert.All(AttackMapping.All, t => Assert.False(string.IsNullOrWhiteSpace(t.Tactics)));
        Assert.Equal("https://attack.mitre.org/techniques/T1547/001/", AttackMapping.RunKeysStartupFolder.Url);
        Assert.Equal("https://attack.mitre.org/techniques/T1685/", AttackMapping.DisableOrModifyTools.Url);
        Assert.All(AttackMapping.Rows.SelectMany(r => r.Tags), tag => Assert.Contains(tag.Technique, AttackMapping.All));
    }

    [Fact]
    public void ImpairDefenses_UsesTheIdsAttackMovedItTo()
    {
        // ATT&CK v18 revoked T1562.001 and T1562.004 in favour of these.
        Assert.Contains(AttackMapping.For("DefenderWatchdog", "REALTIME_OFF"), t => t.Technique.Id == "T1685" && t.Fit == AttackFit.Direct);
        Assert.Contains(AttackMapping.For("FirewallWatchdog", "PROFILE_DISABLED_PUBLIC"), t => t.Technique.Id == "T1686.003");
        Assert.DoesNotContain(AttackMapping.All, t => t.Id.StartsWith("T1562", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("Registry/HKLM/Registry64/Run/Updater", "T1547.001")]
    [InlineData("Registry/HKCU-S-1-5-21-1-2-3-1001/Default/RunOnce/x", "T1547.001")]
    [InlineData(@"Startup/C:\Users\me\AppData\Roaming\Microsoft\Windows\Start Menu\Programs\Startup/a.lnk", "T1547.001")]
    [InlineData(@"ScheduledTasks/S-1-5-18/\Updater", "T1053.005")]
    [InlineData("Services/Updater", "T1543.003")]
    [InlineData("WmiSubscriptions/root/subscription/Binding/a -> b", "T1546.003")]
    public void PersistenceChanges_MapBySource(string resource, string id)
    {
        foreach (var code in new[] { "ENTRY_ADDED", "ENTRY_CHANGED", "VERIFY_SUSPICIOUS" })
        {
            var tag = Assert.Single(AttackMapping.For("Persistence", code, resource));
            Assert.Equal(id, tag.Technique.Id);
        }
    }

    [Theory]
    [InlineData("ENTRY_REMOVED", "Services/Updater")]
    [InlineData("BASELINE_CREATED", "Services")]
    [InlineData("SOURCE_UNAVAILABLE", "Services")]
    [InlineData("ENTRY_ADDED", "SomethingNew/x")]
    [InlineData("ENTRY_ADDED", null)]
    public void PersistenceHealthBaselinesAndRemovals_AreUnmapped(string code, string? resource) =>
        Assert.Empty(AttackMapping.For("Persistence", code, resource));

    [Theory]
    [InlineData(@"C:\Windows\explorer.exe|C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe", "T1059.001")]
    [InlineData(@"C:\Program Files\Microsoft Office\root\Office16\WINWORD.EXE|C:\Windows\System32\MSHTA.EXE", "T1218.005")]
    [InlineData(@"(unknown parent)|C:\Windows\System32\rundll32.exe", "T1218.011")]
    [InlineData(@"C:\x.exe|C:\Windows\System32\wscript.exe", "T1059.005,T1059.007")]
    [InlineData(@"C:\x.exe|C:\Windows\System32\certutil.exe", "T1105,T1140")]
    public void ScriptHostLaunches_MapByHost(string resource, string ids) =>
        Assert.Equal(ids, AttackMapping.Ids(AttackMapping.For("ScriptHostAudit", "SCRIPT_HOST_LAUNCHED", resource)));

    [Fact]
    public void AnUnknownScriptHost_IsRelatedToTheParentTechnique()
    {
        var tag = Assert.Single(AttackMapping.For("ScriptHostAudit", "SCRIPT_HOST_LAUNCHED", @"C:\a.exe|C:\Tools\custom-host.exe"));
        Assert.Equal(("T1059", AttackFit.Related), (tag.Technique.Id, tag.Fit));
    }

    [Theory]
    [InlineData("DefenderWatchdog", "REALTIME_OFF_CLEARED")]
    [InlineData("HostsProxyWatchdog", "PROTECTED_HOST_OVERRIDDEN_CLEARED")]
    [InlineData("DefenderWatchdog", "STATUS_UNAVAILABLE")]
    [InlineData("Hub", "DAILY_SUMMARY")]
    [InlineData("Updater", "UPDATE_AVAILABLE")]
    [InlineData("SomeFutureModule", "ANYTHING")]
    public void RecoveryHealthAndUnknownAlerts_AreUnmapped(string module, string code) =>
        Assert.Empty(AttackMapping.For(module, code, "x"));

    [Fact]
    public void BroadExclusions_MapLikeOtherExclusions() =>
        Assert.Equal("T1685", AttackMapping.Ids(AttackMapping.For("DefenderWatchdog", @"BROAD_EXCLUSION:Path:C:\")));

    [Fact]
    public void Describe_MarksRelatedTechniques()
    {
        var tags = AttackMapping.For("Canary", "CANARY_DELETED");
        Assert.Equal("T1486 Data Encrypted for Impact (related); T1485 Data Destruction (related)", AttackMapping.Describe(tags));
        Assert.Equal("T1486,T1485", AttackMapping.Ids(tags));
    }

    [Fact]
    public void CoverageDoc_ListsEveryMapping()
    {
        var path = Path.Join(RepoRoot(), "docs", "attack-coverage.md");
        var doc = File.ReadAllText(path).ReplaceLineEndings("\n");
        var start = doc.IndexOf(TableStart, StringComparison.Ordinal);
        var end = doc.IndexOf(TableEnd, StringComparison.Ordinal);
        Assert.True(start >= 0 && end > start, $"docs/attack-coverage.md needs the markers {TableStart} and {TableEnd}");

        var expected = Table();
        var actual = doc[(start + TableStart.Length)..end].Trim('\n');
        if (actual != expected && Environment.GetEnvironmentVariable("WATCHLATTICE_UPDATE_DOCS") == "1")
        {
            File.WriteAllText(path, doc[..(start + TableStart.Length)] + "\n" + expected + "\n" + doc[end..]);
            return;
        }
        Assert.Equal(expected, actual);
        Assert.Contains(AttackMapping.AttackVersion, doc);
    }

    /// <summary>One row per technique, listing every alert that is evidence of it.</summary>
    private static string Table()
    {
        var md = new StringBuilder()
            .Append("| Technique | Tactics | Alerts (Event ID) | Fit |\n")
            .Append("|---|---|---|---|\n");
        var rows = AttackMapping.Rows.SelectMany(r => r.Tags.Select(t => (r.Module, r.Code, r.Condition, Tag: t))).ToList();
        foreach (var technique in AttackMapping.All.OrderBy(t => t.Id, StringComparer.Ordinal))
        {
            var mine = rows.Where(r => r.Tag.Technique == technique).ToList();
            if (mine.Count == 0) continue;
            var alerts = mine
                .GroupBy(r => (r.Module, r.Code))
                .Select(g =>
                {
                    var id = AlertEventIds.For(g.Key.Module, g.Key.Code.TrimEnd('*') + (g.Key.Code.EndsWith('*') ? "x" : ""), AlertSeverity.Warning);
                    var conditions = g.Select(r => r.Condition).Where(c => c.Length > 0).Distinct().ToList();
                    return $"{g.Key.Module} `{g.Key.Code}` ({id})" + (conditions.Count == 0 ? "" : " for " + string.Join(", ", conditions));
                });
            var fits = mine.Select(r => r.Tag.Fit).Distinct().OrderBy(f => f).Select(f => f.ToString().ToLowerInvariant());
            md.Append($"| [{technique.Id}]({technique.Url}) {technique.Name} | {technique.Tactics} | {string.Join("<br>", alerts)} | {string.Join(", ", fits)} |\n");
        }
        return md.ToString().TrimEnd('\n');
    }

    private static string RepoRoot()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Join(dir.FullName, "WatchLattice.sln"))) return dir.FullName;
        }
        throw new DirectoryNotFoundException("Could not find WatchLattice.sln above the test output folder.");
    }
}
